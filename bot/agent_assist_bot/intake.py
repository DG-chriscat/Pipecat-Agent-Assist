"""Intake flow (PRD IN-3 to IN-9) as a Pipecat Flow.

Steps, in order (IN-3): greeting -> identity -> reason -> one node per pack question
-> read back -> handoff. The wording and the question list come from the use case
pack (IN-4, `packs/<id>.yaml`).

- Every answer is written to `calls.intake` by the function call that captures it
  (IN-5), before the flow moves on.
- Identity is a function call checked against `members` (IN-6). not_verified and
  not_found callers are flagged and still continue to an agent.
- `request_person` and `report_emergency` are offered on every intake node, so the
  caller can ask for a person (IN-7) or describe an emergency (IN-9) at any time.
  An emergency gets the fixed "hang up and call 911" line, is flagged, and is then
  handed off like any other call so a person sees the flag.
- At the end, the call is marked `ready_for_queue` with an intake summary and the
  HandoffHook is called. The queue (P2-4) implements the hook; the default is a no-op.

Store and hook errors are logged and swallowed: a database hiccup must not drop a
caller mid intake.

No stalls (Nov 16 prod call, where the LLM answered "Correctamundo" in text in
identity_confirm, promised a person, and the call never reached the queue):
- The confirm nodes (identity_confirm, readback) force a tool call on every LLM turn
  (`tool_choice` "required", sent by llm_anthropic.py). Speaking goes through
  `say_to_caller`, so a turn can never end in free text there.
- Fallback in code: if the caller's reply in a confirm node is a plain yes and no
  intake function ran within CHECK_AFTER_TURN_SECS, verify_identity / confirm_summary
  run anyway.
- Watchdog: MAX_TURNS_WITHOUT_FUNCTION caller turns in one node with no intake
  function, or INTAKE_MAX_SECS of intake, hands the call to the queue with what was
  captured and the intake_stalled flag (IN-7: the caller always reaches a person).
- Every node change and function call logs a `[flow]` line (values never logged).
"""


async def uninterruptible_tts_say(action: dict, flow_manager: FlowManager) -> None:
    """Replaces Flows' built-in `tts_say` action (registered in bot.build_worker).

    Flows queues the line and then an ActionFinishedFrame that marks the action done;
    the next node change waits for it. That marker is an ordinary interruptible frame,
    so a caller who talks over the line (often while the TTS holds frames until the
    line's audio is out) gets it dropped: the flow then waits forever, the next node's
    task and tools never reach the LLM, and the caller's answer goes to the old node.
    Seen live in P5-5 (the identity read back looped on save_identity). The line itself
    stays interruptible; only the marker must get through.
    """
    from pipecat.flows.actions import ActionFinishedFrame

    text = action.get("text")
    if not text:
        logger.error("[flow] tts_say without text")
        return
    worker = flow_manager.worker
    flow_manager._action_manager._increment_ongoing_actions_count()
    await worker.queue_frame(
        TTSSpeakFrame(text=text, append_to_context=action.get("append_text_to_context", True))
    )
    done = ActionFinishedFrame()
    done.interruptible = False
    await worker.queue_frame(done)


@dataclass(frozen=True)
class IntakeHandoff:
    """What the queue receives when intake ends."""

    call_id: str
    session_id: str
    outcome: Outcome
    summary: str
    intake: dict[str, Any] = field(default_factory=dict)
    identity_result: str | None = None
    member_id: str | None = None
    flags: tuple[str, ...] = ()
    # Which identity details matched (calls.IdentityCheck.checks); None if never checked.
    identity_checks: tuple[str, ...] | None = None


@runtime_checkable
class HandoffHook(Protocol):
    """Implemented by the queue (P2-4). Called once per call when intake ends."""

    async def on_intake_complete(self, handoff: IntakeHandoff) -> None: ...


class NoopHandoff:
    """Default hook until the queue exists: logs and does nothing."""

    async def on_intake_complete(self, handoff: IntakeHandoff) -> None:
        logger.info(f"[intake] handoff (no queue yet): {handoff.outcome} call={handoff.call_id}")


def build_summary(intake: dict[str, Any], identity_result: str | None) -> str:
    """Plain summary from whatever was captured, used when the caller skips read back."""
    parts = []
    if name := intake.get("full_name"):
        parts.append(f"Caller {name}")
    if mid := intake.get("member_id"):
        parts.append(f"member ID {mid}")
    if identity_result:
        parts.append(f"identity {identity_result.replace('_', ' ')}")
    if reason := intake.get("reason"):
        parts.append(f"calling about: {reason}")
    if emergency := intake.get("emergency"):
        parts.append(f"described an emergency: {emergency}")
    skip = {"full_name", "member_id", "dob", "reason", "emergency", "summary"}
    for key, value in intake.items():
        if key not in skip and value:
            parts.append(f"{key.replace('_', ' ')}: {value}")
    return (". ".join(parts) + ".") if parts else "No intake details captured."


class IntakeSession:
    """One caller's intake: builds the flow nodes and owns the call record."""

    def __init__(
        self,
        *,
        pack: Pack,
        store: CallStore,
        session_id: str,
        handoff: HandoffHook | None = None,
        identity_tuning: Callable[[bool], Awaitable[None]] | None = None,
        intake_max_secs: float = INTAKE_MAX_SECS,
        check_after_turn_secs: float = CHECK_AFTER_TURN_SECS,
        greeting: str = GREETING,
        identity_read_back: bool = True,
    ):
        self.pack = pack
        self.store = store
        self.session_id = session_id
        self.handoff = handoff or NoopHandoff()
        # P5-5 settings: the greeting (keeps the IN-2 disclosure, checked on save) and
        # whether the name and member ID are read back before the identity check.
        self.greeting = greeting
        self.identity_read_back = identity_read_back
        # Turns the identity step's STT settings on/off (stt_tuning.IdentitySTTTuning).
        self.identity_tuning = identity_tuning
        self.call_id: str | None = None
        self.intake: dict[str, Any] = {}
        self.identity: IdentityCheck | None = None
        self.flags: list[str] = []
        self.handed_off: Outcome | None = None
        self._confirm_fixes = 0  # re-asks in identity_confirm (IN-6 cap)
        self._identity_asks = 0  # save_identity calls refused for a missing field
        self._tuned = False
        # Stall guards (module doc). `node` is the node the Flow is in (entry action).
        self.flow_manager: FlowManager | None = None
        self.node: str | None = None
        self.intake_max_secs = intake_max_secs
        self.check_after_turn_secs = check_after_turn_secs
        self._progress = 0  # intake function calls so far (say_to_caller excluded)
        self._turns_without_progress = 0
        self._refused_lines = 0
        self._tasks: set[asyncio.Task] = set()
        self._node_ids = itertools.count(1)
        self._node_token: int | None = None
        self._superseded: set[int] = set()
        # Fragments of one caller reply (see on_caller_turn).
        self._awaiting_bot = False
        self._reply = ""
        self._last_fragment = 0.0
        # The caller's last few turns, for the emergency gate in the identity steps.
        self._recent_caller: deque[str] = deque(maxlen=3)

    # ---- call record -------------------------------------------------------

    async def start(self) -> str:
        """Create (or reuse) this session's calls row."""
        if self.call_id is None:
            self.call_id = await self.store.create_call(self.session_id)
            logger.info(f"[intake] call {self.call_id} session={self.session_id}")
        return self.call_id

    async def _safe(self, what: str, coro) -> None:
        try:
            await coro
        except Exception as e:  # noqa: BLE001 - never drop the caller over a DB error
            logger.error(f"[intake] {what} failed: {type(e).__name__}: {e}")

    async def _save(self, fields: dict[str, Any]) -> None:
        self.intake.update(fields)
        logger.info(f"[intake] saved {sorted(fields)}")
        await self._safe("save_intake", self.store.save_intake(self.call_id, fields))

    async def _flag(self, flag: str) -> None:
        if flag not in self.flags:
            self.flags.append(flag)
        await self._safe("add_flag", self.store.add_flag(self.call_id, flag))

    async def _finish(self, outcome: Outcome, summary: str | None = None) -> None:
        """Mark ready_for_queue and call the hook, once per call."""
        if self.handed_off is not None:
            return
        self.handed_off = outcome
        # Details given but intake ended before the caller confirmed the read back
        # (asked for a person, emergency): check them anyway so the agent sees a result.
        if self.identity is None and self.intake.get("full_name"):
            await self._check_identity()
        await self._tune(False)
        summary = summary or build_summary(self.intake, self._identity_result())
        self.intake["summary"] = summary
        await self._safe(
            "mark_ready_for_queue", self.store.mark_ready_for_queue(self.call_id, summary)
        )
        handoff = IntakeHandoff(
            call_id=self.call_id,
            session_id=self.session_id,
            outcome=outcome,
            summary=summary,
            intake=dict(self.intake),
            identity_result=self._identity_result(),
            member_id=self.identity.member_id if self.identity else None,
            flags=tuple(self.flags),
            identity_checks=self.identity.checks if self.identity else None,
        )
        logger.info(f"[intake] ready_for_queue outcome={outcome}")
        await self._safe("handoff hook", self.handoff.on_intake_complete(handoff))

    def _identity_result(self) -> str | None:
        return self.identity.result if self.identity else None

    async def _tune(self, active: bool) -> None:
        if self.identity_tuning is not None and active != self._tuned:
            self._tuned = active
            await self._safe("identity STT tuning", self.identity_tuning(active))

    async def _on_identity_entered(self, action: dict, flow_manager: FlowManager) -> None:
        await self._tune(True)

    # ---- stall guards: node entry, [flow] log, fallback, watchdog ---------------

    def _finalize(self, node: NodeConfig) -> NodeConfig:
        """Every node: an entry action (tracks the node, sets tool_choice, logs) and
        function handlers wrapped to log `[flow]` lines and count progress."""
        name = node["name"]
        token = next(self._node_ids)
        node["functions"] = [self._wrap(name, token, f) for f in node.get("functions", [])]
        entered = {
            "type": "intake_node_entered",
            "handler": self._on_node_entered,
            "node": name,
            "token": token,
        }
        # First, so it runs before any tts_say (a custom action after tts_say would
        # wait for the speech to finish).
        node["pre_actions"] = [entered, *node.get("pre_actions", [])]
        return node

    def _wrap(self, node: str, token: int, f: FlowsFunctionSchema) -> FlowsFunctionSchema:
        handler, name = f.handler, f.name

        async def logged(args: FlowArgs, flow_manager: FlowManager):
            # Argument names only: values can be PHI.
            logger.info(f"[flow] {node}: function {name}({', '.join(sorted(args))})")
            if token in self._superseded:
                # The code already moved the flow on from this node (fallback or
                # watchdog) while the LLM was still answering: ignore the late call.
                logger.warning(f"[flow] {name} from {node} ignored: now in {self.node}")
                return {"status": "ignored, the step is over"}, NO_RESPONSE
            if name != SAY_TO_CALLER:
                self._progress += 1
                self._turns_without_progress = 0
            result = await handler(args, flow_manager)
            nxt = result[1] if isinstance(result, tuple) else None
            if isinstance(nxt, dict):
                logger.info(f"[flow] {node}: {name} -> {nxt.get('name')}")
            return result

        return dataclasses.replace(f, handler=logged)

    async def _on_node_entered(self, action: dict, flow_manager: FlowManager) -> None:
        node = action["node"]
        self.node = node
        self._node_token = action.get("token")
        self._turns_without_progress = 0
        self._awaiting_bot = False
        self._refused_lines = 0
        # Confirm nodes: every LLM turn must be a function call (llm_anthropic.py).
        choice = "required" if node in CONFIRM_NODES else "auto"
        logger.info(f"[flow] node -> {node} (tool_choice={choice})")
        worker = getattr(flow_manager, "worker", None)
        if worker is not None:
            frame = LLMSetToolChoiceFrame(tool_choice=choice)
            frame.interruptible = False
            await worker.queue_frames([frame])

    def _say_function(self) -> FlowsFunctionSchema:
        return FlowsFunctionSchema(
            name=SAY_TO_CALLER,
            description=(
                "Say something to the caller, for example to ask them to repeat or to "
                "clarify. This is the only way to speak in this step."
            ),
            properties={"text": {"type": "string", "description": "One or two short sentences."}},
            required=["text"],
            handler=self._on_say,
        )

    async def _on_say(self, args: FlowArgs, flow_manager: FlowManager):
        text = str(args.get("text") or "").strip()
        if _HANDOFF_PROMISE.search(text):
            self._refused_lines += 1
            logger.warning(f"[flow] {self.node}: refused a line that promises a transfer")
            if self._refused_lines > 1:
                return {"error": "not said"}, NO_RESPONSE
            return {
                "error": (
                    "Not said: never promise a transfer or that a person is joining. "
                    "Call the step's function instead, or ask your question again."
                )
            }, None
        worker = getattr(flow_manager, "worker", None)
        if text and worker is not None:
            await worker.queue_frames([TTSSpeakFrame(text)])
        # Spoken directly: no further LLM turn until the caller answers.
        return {"said": True}, NO_RESPONSE

    def _spawn(self, coro) -> None:
        task = asyncio.create_task(coro)
        self._tasks.add(task)
        task.add_done_callback(self._tasks.discard)

    def start_watchdog(self, flow_manager: FlowManager) -> None:
        """Arm the intake time budget. Called once the greeting is queued."""
        self.flow_manager = flow_manager
        self._spawn(self._intake_timer())

    async def close(self) -> None:
        for task in list(self._tasks):
            task.cancel()
        self._tasks.clear()

    async def _intake_timer(self) -> None:
        await asyncio.sleep(self.intake_max_secs)
        await self._stall(f"intake over {self.intake_max_secs:.0f} s")

    def on_bot_turn(self) -> None:
        """The bot finished speaking (assistant aggregator): the next caller turn is new."""
        self._awaiting_bot = False

    async def on_caller_turn(self, text: str) -> None:
        """A caller turn ended (user aggregator). Arms the fallback and turn watchdog.

        One spoken answer can end in several turn events (STT splits it), so the turn
        count goes up once per bot reply, and the yes check looks at everything the
        caller said since the bot last spoke.
        """
        node = self.node
        if text.strip():
            self._recent_caller.append(text.strip())
        if self.handed_off is not None or node is None or node in _NOT_INTAKE:
            return
        new_turn = not self._awaiting_bot or time.monotonic() - self._last_fragment > (
            REPLY_FRAGMENT_SECS
        )
        self._last_fragment = time.monotonic()
        if new_turn:
            self._awaiting_bot = True
            self._turns_without_progress += 1
            self._reply = ""
        self._reply = f"{self._reply} {text}".strip()
        turns, seq, token = self._turns_without_progress, self._progress, self._node_token
        affirmative = node in CONFIRM_NODES and is_affirmative(self._reply)
        logger.info(
            f"[flow] {node}: caller turn {turns} without progress"
            + ("" if new_turn else " (continued)")
            + (" (affirmative)" if affirmative else "")
        )
        if new_turn or affirmative:
            self._spawn(self._check_turn(node, token, seq, turns, affirmative))

    async def _check_turn(
        self, node: str, token: int | None, seq: int, turns: int, affirmative: bool
    ) -> None:
        await asyncio.sleep(self.check_after_turn_secs)
        if self.handed_off is not None or self._node_token != token or self._progress != seq:
            return  # the LLM called a function, or the flow moved on
        try:
            # Re-checked: the caller may have gone on ("yes... but my name is...").
            if affirmative and is_affirmative(self._reply):
                await self._confirm_in_code(node)
            elif turns >= MAX_TURNS_WITHOUT_FUNCTION and turns == self._turns_without_progress:
                await self._stall(f"{turns} caller turns in {node} without a function call")
        except Exception as e:  # noqa: BLE001 - the watchdog must not kill the call
            logger.error(f"[flow] {node}: stall guard failed: {type(e).__name__}: {e}")

    def _supersede(self) -> None:
        """The code moves the flow on: late LLM calls from this node are ignored."""
        if self._node_token is not None:
            self._superseded.add(self._node_token)

    async def _confirm_in_code(self, node: str) -> None:
        """The caller said yes to a read back and the LLM called nothing: confirm."""
        logger.warning(f"[flow] {node}: caller said yes but no function ran; confirming in code")
        self._supersede()
        self._progress += 1
        fm = self.flow_manager
        if node == "identity_confirm":
            _, nxt = await self._on_verify_identity({}, fm)
        else:
            _, nxt = await self._on_confirm({}, fm)
        logger.info(f"[flow] {node}: fallback -> {nxt.get('name') if nxt else None}")
        if fm is not None and isinstance(nxt, dict):
            await fm.set_node_from_config(nxt)

    async def _stall(self, why: str) -> None:
        """Hand off with what we have, flagged intake_stalled (IN-7)."""
        if self.handed_off is not None:
            return
        logger.warning(f"[flow] intake stalled in {self.node}: {why}; handing off")
        self._supersede()
        await self._flag(FLAG_INTAKE_STALLED)
        await self._finish("completed")
        if self.flow_manager is not None:
            await self.flow_manager.set_node_from_config(self.handoff_node())

    # ---- shared functions (IN-7, IN-9) ----------------------------------------

    def _escape_functions(self, *, identity: bool = False) -> list[FlowsFunctionSchema]:
        """request_person and report_emergency, on every intake node. In the identity
        steps (`identity=True`) report_emergency needs explicit emergency words."""
        emergency_desc = (
            "The caller described a medical emergency happening now. Call immediately. "
            "Do not give medical advice."
        )
        if identity:
            emergency_desc += (
                " A name, date of birth, or member ID is never an emergency: only call this "
                "if the caller uses emergency words (chest pain, can't breathe, bleeding, "
                "overdose, suicide, 911, ambulance)."
            )
        return [
            FlowsFunctionSchema(
                name="request_person",
                description=(
                    "The caller asked to talk to a person, human, agent, or representative. "
                    "Call immediately; intake stops and the call goes to the queue."
                ),
                properties={},
                required=[],
                handler=self._on_request_person,
            ),
            FlowsFunctionSchema(
                name="report_emergency",
                description=emergency_desc,
                properties={
                    "description": {
                        "type": "string",
                        "description": "Short description of the emergency in the caller's words.",
                    }
                },
                required=["description"],
                handler=self._on_identity_emergency if identity else self._on_emergency,
            ),
        ]

    async def _on_request_person(self, args: FlowArgs, flow_manager: FlowManager):
        await self._flag(FLAG_ASKED_FOR_PERSON)
        await self._finish("asked_for_person")
        return {"status": "connecting"}, self.handoff_node()

    async def _on_emergency(self, args: FlowArgs, flow_manager: FlowManager):
        await self._flag(FLAG_EMERGENCY)
        await self._save({"emergency": str(args.get("description", "")).strip()})
        await self._finish("emergency")
        return {"status": "emergency_flagged"}, self.emergency_node()

    async def _on_identity_emergency(self, args: FlowArgs, flow_manager: FlowManager):
        """report_emergency in the identity steps, where the caller reads out a name, a
        date, and an ID. There the LLM has called it on a plain answer (PR #48, identity
        v2 harness), so it needs explicit emergency words from the caller, or a symptom
        in the description. Everywhere else the LLM's call stands (IN-9)."""
        description = str(args.get("description", "")).strip()
        heard = " ".join(self._recent_caller)
        if not (_EMERGENCY_WORDS.search(heard) or _EMERGENCY_WORDS.search(description)):
            logger.warning("[flow] report_emergency refused in identity: no emergency words")
            return {
                "error": (
                    "not an emergency: the caller only gave their details. Do not call "
                    "report_emergency unless they describe an emergency."
                )
            }, None
        return await self._on_emergency(args, flow_manager)

    # ---- nodes ---------------------------------------------------------------

    def _task(self, content: str) -> list[dict]:
        return [{"role": "developer", "content": content}]

    def greeting_node(self) -> NodeConfig:
        """Fixed TTS greeting (IN-1, IN-2). No LLM call; start_intake moves on to identity."""
        return self._finalize(
            {
                "name": "greeting",
                "role_message": ROLE_MESSAGE,
                "task_messages": self._task("The greeting has been spoken."),
                "functions": [],
                "pre_actions": [{"type": "tts_say", "text": self.greeting}],
                "respond_immediately": False,
            }
        )

    def identity_node(self) -> NodeConfig:
        return self._finalize(
            {
                "name": "identity",
                "task_messages": self._task(
                    f"{self.pack.identity.prompt} When you have all three, call save_identity "
                    "right away without saying anything; the next step "
                    f"{'reads them back' if self.identity_read_back else 'checks them'}. Pass "
                    "the date of birth as YYYY-MM-DD; a date written like 03/12/1984 is "
                    "MM/DD/YYYY. Pass the member ID as letters and digits with no spaces. "
                    + (
                        "If part of the member ID seems missing, save what you heard; the "
                        "caller can correct it at the read back."
                        if self.identity_read_back
                        else "If part of the member ID seems missing, ask for it once."
                    )
                    + " A name, date of birth, or member ID is never an emergency."
                ),
                "functions": [
                    FlowsFunctionSchema(
                        name="save_identity",
                        description=(
                            "Save the caller's name, date of birth, and member ID once you have "
                            "all three. They are read back to the caller before the check."
                        ),
                        properties=_identity_properties(),
                        required=["full_name", "date_of_birth", "member_id"],
                        handler=self._on_save_identity,
                    ),
                    *self._escape_functions(identity=True),
                ],
                # Identity STT settings on for this step only (stt_tuning.py).
                "pre_actions": [{"type": "identity_stt_on", "handler": self._on_identity_entered}],
            }
        )

    async def _on_save_identity(self, args: FlowArgs, flow_manager: FlowManager):
        fields = _identity_fields(args)
        if missing := [k for k, v in fields.items() if not v]:
            self._identity_asks += 1
            if self._identity_asks <= MAX_IDENTITY_FIXES:
                return {"error": f"missing {', '.join(missing)}; ask the caller for it"}, None
            # Asked once already: check with what we have and move on (incomplete).
            if present := {k: v for k, v in fields.items() if v}:
                await self._save(present)
            return await self._on_verify_identity({}, flow_manager)
        await self._save(fields)
        self._confirm_fixes = 0
        if not self.identity_read_back:
            # P5-5: read back off in Settings: check the details as saved.
            return await self._on_verify_identity({}, flow_manager)
        return {"saved": "identity"}, self.identity_confirm_node()

    def identity_confirm_node(self) -> NodeConfig:
        """Read the name and member ID back before the check (identity card).

        STT mishears spelled IDs and names (docs/spikes/phase2.md). A fixed TTS line
        (no LLM wording, so the ID is always in groups and the DOB is never said) lets
        the caller correct them. One fix (IN-6 v2): a correction checks right away, and
        a second free form re-ask checks with what was saved, so a misheard name never
        loops (docs/spikes/identity.md) and intake stays under the 2 minute target.
        """
        text = READBACK_LINE.format(
            name=self.intake.get("full_name") or "your name",
            member_id=speak_member_id(self.intake.get("member_id", "")) or "not caught",
        )
        return self._finalize(
            {
                "name": "identity_confirm",
                "task_messages": self._task(
                    f'You just said: "{text}" Every reply in this step is a function call. '
                    "If the caller says yes in any words (yes, yep, correct, that's right, "
                    "correctamundo, sounds good), call verify_identity right away without "
                    "saying anything. If they correct their name, member ID, or date of "
                    "birth, call correct_identity right away without saying anything, with "
                    "only the corrected values (member ID as letters and digits, no spaces). "
                    "If they spell a name letter by letter, join the letters into the name. "
                    "Only if you cannot tell, use say_to_caller to ask if the details are right."
                ),
                "functions": [
                    FlowsFunctionSchema(
                        name="verify_identity",
                        description="The caller confirmed the read back. Checks their identity.",
                        properties={},
                        required=[],
                        handler=self._on_verify_identity,
                    ),
                    FlowsFunctionSchema(
                        name="correct_identity",
                        description="The caller corrected their name, member ID, or date of birth.",
                        properties=_identity_properties(),
                        required=[],
                        handler=self._on_correct_identity,
                    ),
                    dataclasses.replace(self._say_function(), handler=self._on_identity_say),
                    *self._escape_functions(identity=True),
                ],
                "pre_actions": [{"type": "tts_say", "text": text}],
                "respond_immediately": False,
            }
        )

    async def _on_correct_identity(self, args: FlowArgs, flow_manager: FlowManager):
        """One correction (IN-6 v2): save it, then check and move on. No second read
        back: a name STT keeps mishearing is left for the agent to confirm (IN-13)."""
        fields = {k: v for k, v in _identity_fields(args).items() if v}
        if fields:
            await self._save(fields)
        return await self._on_verify_identity({}, flow_manager)

    async def _on_identity_say(self, args: FlowArgs, flow_manager: FlowManager):
        """say_to_caller in identity_confirm. A re-ask in the LLM's own words counts
        toward the one fix: the second one checks with what was saved instead."""
        if self._confirm_fixes >= MAX_IDENTITY_FIXES:
            logger.info("[flow] identity_confirm: re-ask cap reached; checking")
            return await self._on_verify_identity({}, flow_manager)
        result = await self._on_say(args, flow_manager)
        if isinstance(result, tuple) and isinstance(result[0], dict) and result[0].get("said"):
            self._confirm_fixes += 1
        return result

    async def _on_verify_identity(self, args: FlowArgs, flow_manager: FlowManager):
        check = await self._check_identity()
        await self._tune(False)
        if check.result == "verified":
            note = "Identity verified. Thank them briefly and move on."
        else:
            note = (
                "Identity could not be confirmed. Do not say which detail did not match, "
                "and do not dwell on it; just move on."
            )
        return {"identity": check.result, "note": note}, self.reason_node()

    async def _check_identity(self) -> IdentityCheck:
        """Check the saved details against members (IN-6), record and flag the result.

        A detail still missing (after the one ask) makes the result `incomplete`; what
        did match is kept for the agent's verification step (IN-13)."""
        name = self.intake.get("full_name", "")
        dob = self.intake.get("dob", "")
        member_id = self.intake.get("member_id", "")
        try:
            check = await self.store.verify_identity(name, dob, member_id)
        except Exception as e:  # noqa: BLE001
            logger.error(f"[intake] identity check failed: {type(e).__name__}: {e}")
            check = IdentityCheck("not_found", None)
        if not (name and dob and member_id):
            check = dataclasses.replace(check, result="incomplete")
        self.identity = check
        await self._safe(
            "set_identity", self.store.set_identity(self.call_id, check.result, check.member_id)
        )
        flag = {
            "not_verified": FLAG_NOT_VERIFIED,
            "not_found": FLAG_NOT_FOUND,
            "close_match": FLAG_CLOSE_MATCH,
            "incomplete": FLAG_INCOMPLETE,
        }.get(check.result)
        if flag:
            await self._flag(flag)
        return check

    def reason_node(self) -> NodeConfig:
        return self._finalize(
            {
                "name": "reason",
                "task_messages": self._task(
                    f"{self.pack.reason.prompt} When they answer, call save_reason with a short "
                    "summary in their words."
                ),
                "functions": [
                    FlowsFunctionSchema(
                        name="save_reason",
                        description="Save why the caller is calling.",
                        properties={
                            "reason": {"type": "string", "description": "Reason in a few words."}
                        },
                        required=["reason"],
                        handler=self._on_reason,
                    ),
                    *self._escape_functions(),
                ],
            }
        )

    async def _on_reason(self, args: FlowArgs, flow_manager: FlowManager):
        await self._save({"reason": str(args.get("reason", "")).strip()})
        return {"saved": "reason"}, self._node_after(None)

    def _node_after(self, key: str | None) -> NodeConfig:
        keys = [q.key for q in self.pack.questions]
        idx = 0 if key is None else keys.index(key) + 1
        return self.question_node(keys[idx]) if idx < len(keys) else self.readback_node()

    def question_node(self, key: str) -> NodeConfig:
        q = next(q for q in self.pack.questions if q.key == key)

        async def on_answer(args: FlowArgs, flow_manager: FlowManager):
            await self._save({q.key: str(args.get("answer", "")).strip()})
            return {"saved": q.key}, self._node_after(q.key)

        return self._finalize(
            {
                "name": f"question_{q.key}",
                "task_messages": self._task(
                    f'Ask this, in your own words if needed: "{q.ask}" When they answer, call '
                    f'save_answer. If they do not know, save "unknown".'
                ),
                "functions": [
                    FlowsFunctionSchema(
                        name="save_answer",
                        description=f"Save the answer: {q.description}",
                        properties={"answer": {"type": "string", "description": q.description}},
                        required=["answer"],
                        handler=on_answer,
                    ),
                    *self._escape_functions(),
                ],
            }
        )

    def _editable_fields(self) -> list[str]:
        return ["full_name", "dob", "member_id", "reason", *[q.key for q in self.pack.questions]]

    def readback_node(self) -> NodeConfig:
        captured = "; ".join(
            f"{k}: {self.intake[k]}" for k in self._editable_fields() if self.intake.get(k)
        )
        return self._finalize(
            {
                "name": "readback",
                "task_messages": self._task(
                    f"{self.pack.readback.prompt} Captured so far: {captured or 'nothing'}. "
                    "Do not spell out the member ID or the claim number; both are on file, "
                    "so leave them out. "
                    "Every reply in this step is a function call: speak only through "
                    "say_to_caller, so read the summary back with say_to_caller. "
                    "If the caller corrects something, call correct_field, then read back the "
                    "fixed part with say_to_caller. When they agree it is right in any words "
                    "(yes, yep, correct, that's right, sounds good), call confirm_summary."
                ),
                "functions": [
                    FlowsFunctionSchema(
                        name="correct_field",
                        description="Fix one captured field the caller corrected.",
                        properties={
                            "field": {"type": "string", "enum": self._editable_fields()},
                            "value": {"type": "string", "description": "The corrected value."},
                        },
                        required=["field", "value"],
                        handler=self._on_correct,
                    ),
                    FlowsFunctionSchema(
                        name="confirm_summary",
                        description="The caller confirmed the read back. Ends intake.",
                        properties={
                            "summary": {
                                "type": "string",
                                "description": "One or two sentence summary for the agent.",
                            }
                        },
                        required=["summary"],
                        handler=self._on_confirm,
                    ),
                    self._say_function(),
                    *self._escape_functions(),
                ],
            }
        )

    async def _on_correct(self, args: FlowArgs, flow_manager: FlowManager):
        name = str(args.get("field", ""))
        if name not in self._editable_fields():
            return {"error": f"unknown field {name!r}"}, None
        value = str(args.get("value", "")).strip()
        if name == "member_id":
            value = normalize_member_id(value)
        await self._save({name: value})
        return {"saved": name}, None

    async def _on_confirm(self, args: FlowArgs, flow_manager: FlowManager):
        summary = str(args.get("summary", "")).strip() or None
        await self._finish("completed", summary)
        return {"status": "ready_for_queue"}, self.handoff_node()

    def handoff_node(self) -> NodeConfig:
        return self._finalize(
            {
                "name": "handoff",
                "task_messages": self._task(
                    "Intake is over and a person is being connected. If the caller speaks, say "
                    "briefly that a person will be with them shortly. Do not ask more questions."
                ),
                "functions": [],
                "pre_actions": [{"type": "tts_say", "text": HANDOFF_LINE}],
                "respond_immediately": False,
            }
        )

    def emergency_node(self) -> NodeConfig:
        return self._finalize(
            {
                "name": "emergency",
                "task_messages": self._task(
                    "The caller described an emergency and was told to hang up and call 911. "
                    "If they speak again, repeat that they should call 911 now. No medical advice."
                ),
                "functions": [],
                "pre_actions": [{"type": "tts_say", "text": EMERGENCY_LINE}],
                "respond_immediately": False,
            }
        )

    def all_nodes(self) -> list[NodeConfig]:
        """The intake steps in order (IN-3). For tests and docs."""
        return [
            self.greeting_node(),
            self.identity_node(),
            self.reason_node(),
            *[self.question_node(q.key) for q in self.pack.questions],
            self.readback_node(),
        ]
